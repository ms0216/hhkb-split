"""プレート ／ ケース ／ 基板 が共有する「凍結すべき境界」。

ケースは 3Dプリントなので何度でも刷り直せるが、プレートと基板は JLCPCB へ
発注するため作り直すと時間と費用がかかる。両者の接点だけをここに集め、
どのモジュールもこの値を参照する。**基板を発注する前にここを確定させる。**

含めるもの:
  - 外形（プレート＝ケース＝基板の輪郭の基準）
  - 取付ネジの位置と径
  - キー開口の寸法

含めないもの（ケース側だけの都合で変えてよいもの）:
  - 壁厚・床厚・傾斜・電池室・チルト脚・三脚ナット・ゴム足
"""

from math import cos, radians

# --------------------------------------------------------------------------
# 外形
# --------------------------------------------------------------------------
PLATE_MARGIN = 4.0       # キー外形からプレート外形までの余白（片側）
CORNER_R = 3.0

# 打鍵面の傾斜。プレートは平らに作って傾けて載せるので、
# 平面図（＝ケースの外形）では奥行が cos(TILT) 倍に縮む。
# これを見落とすとプレートがケースのリムを覆いきれない。
TILT_DEG = 7.3


def plan_depth(plate_depth):
    """平らなプレートを傾けたときの、平面図での奥行。"""
    return plate_depth * cos(radians(TILT_DEG))


def to_plan(pos):
    """プレート座標（平ら）の点を、平面図の座標へ写す。"""
    x, y = pos
    return (x, y * cos(radians(TILT_DEG)))

# --------------------------------------------------------------------------
# スイッチ開口
# --------------------------------------------------------------------------
SWITCH_CUTOUT = 14.0     # MX 標準
PLATE_T = 1.5

# --------------------------------------------------------------------------
# 取付ネジ（M2）
#
# ケース側はボスに下穴を切ってタッピング、プレート側はバカ穴。
# 位置は外周に沿って 6 箇所。キー開口と干渉しない位置に置く。
# --------------------------------------------------------------------------
M2_BOSS_D = 5.0          # ボス外径
M2_PILOT_D = 1.7         # ケース側の下穴（タッピング）
M2_CLEAR_D = 2.4         # プレート側のバカ穴（M2 に 0.4mm の逃げ）
BOSS_WALL_OVERLAP = 1.0  # ボスを壁にめり込ませる量。接線接触を避けるため
CASE_WALL = 2.4          # ボス位置の算出に要るのでここに置く


def boss_positions(w, h):
    """取付ネジの位置。プレートとケースで必ず同じ値を使う。

    四隅と長辺の中央。壁に BOSS_WALL_OVERLAP だけめり込ませた位置に
    ボス中心を置く（ちょうど接する位置だと非多様体メッシュになる）。
    """
    ix = w / 2 - CASE_WALL - M2_BOSS_D / 2 + BOSS_WALL_OVERLAP
    iy = h / 2 - CASE_WALL - M2_BOSS_D / 2 + BOSS_WALL_OVERLAP
    return [(-ix, -iy), (ix, -iy), (-ix, iy), (ix, iy), (0.0, -iy), (0.0, iy)]


def boss_positions_plan(w, plate_depth):
    """ケース側のボス位置。プレート側の穴を平面図へ写したもの。

    プレートは傾いて載るので、平らな板の上の点は平面図では Y が縮む。
    同じ関数から導くことで、プレートの穴とケースのボスが必ず一致する。
    """
    return [to_plan(p) for p in boss_positions(w, plate_depth)]
