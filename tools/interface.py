PCB_POST_PILOT_D = 1.6   # 下穴（M2 のタッピング。熱圧入インサートは長さ 4.0mm で入らない）


def pcb_mount_positions(half):
    """本体基板をプレートへ締める位置。**基板・プレート・組み立てが同じ値を使う。**"""
    if half not in PCB_MOUNT_POSITIONS:
        raise ValueError(f"half は 'left' か 'right'。渡された値: {half!r}")
    return list(PCB_MOUNT_POSITIONS[half])


MOUNT_POSITIONS = {
    "left":  [(-60.00, -51.50), (0.00, -51.50), (60.00, -51.50)],
    "right": [(-75.00, -51.50), (0.00, -51.50), (75.00, -51.50)],
}


def boss_positions(half):
    """取付ネジの位置。プレートとケースと基板で必ず同じ値を使う。"""
    if half not in MOUNT_POSITIONS:
        raise ValueError(f"half は 'left' か 'right'。渡された値: {half!r}")
    return list(MOUNT_POSITIONS[half])


def boss_positions_plan(half):
    """ケース側のボス位置。プレート側の穴を平面図へ写したもの。

    プレートは傾いて載るので、平らな板の上の点は平面図では Y が縮む。
    同じ関数から導くことで、プレートの穴とケースのボスが必ず一致する。
    """
    return [to_plan(p) for p in boss_positions(half)]


