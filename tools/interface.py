"""プレート ／ ケース ／ 基板 が共有する「凍結すべき境界」。

ケースは 3Dプリントなので何度でも刷り直せるが、プレートと基板は JLCPCB へ
発注するため作り直すと時間と費用がかかる。両者の接点だけをここに集め、
どのモジュールもこの値を参照する。**基板を発注する前にここを確定させる。**

含めるもの:
  - 外形（プレート＝ケース＝基板の輪郭の基準）
  - 取付ネジの位置と径
  - キー開口の寸法

含めないもの（ケース側だけの都合で変えてよいもの）:
  - 壁厚・床厚・傾斜・電池室・チルト脚・三脚ナット・ゴム足
"""

from math import cos, radians, sin

# --------------------------------------------------------------------------
# 外形
# --------------------------------------------------------------------------
# キー外形からプレート外形までの余白（片側）。
#
# **実機は左右と前後で違う。** 一律にすると前後が狭くなり、取付ネジを置く
# 余地が無くなる（実際にそうなり、取付穴が基板の外形を 0.3mm はみ出していた）。
#
#   幅   294mm − キー 15u(285.75mm) → 片側 4.125mm
#   奥行 108mm − キー  5u( 95.25mm) → 片側 6.375mm
#
# いずれも PFU 公式の外形寸法から導いた値。奥行 108mm は電池の出っ張りを
# 含まない本体部分（120mm は出っ張り込み）。docs/hardware/dimensions.md 参照。
#
# この値を一律に戻すと、実機の外形から外れるうえにネジが置けなくなる。
PLATE_MARGIN_X = 4.125   # 左右
PLATE_MARGIN_Y = 6.375   # 前後
CORNER_R = 3.0


def plate_size(key_w, key_h):
    """キー領域の外形から、**ケースの外形**を出す。

    左右と前後で余白が違うので、必ずこの関数を通す。

    **名前は歴史的なもの。** かつてプレートがそのままケースの天板だったので
    両者は同じだった。上ケースを足した今、プレートはこれより
    BEZEL_WALL のぶん小さい（switch_plate_size を使う）。
    """
    return key_w + PLATE_MARGIN_X * 2, key_h + PLATE_MARGIN_Y * 2


# 上ケースの座ぐりとプレートの縁の隙間。**印刷した部品どうしの嵌合。**
# gen_case.CLEARANCE と同じ値・同じ意味なので、出所をここ 1 つにする
# （プレートとケースの両方が読むため。gen_case はここから import する）。
CLEARANCE = 0.2


def switch_plate_size(key_w, key_h):
    """スイッチプレートの外形（**平らな状態**の寸法）。

    **平面図で決める。**プレートは傾けて上ケースの座ぐりへ落とし込むので、
    収まるかどうかは平面図での占有で決まる。傾けると

        平面での奥行 = 平らな奥行 × cos(TILT) ＋ 板厚 × sin(TILT)

    となり、**板厚のぶん平面での占有が増える**（1.5 × sin7.3° = 0.19mm）。

    以前はここを使わず、build_plate が「平らな奥行 − 壁×2」を自前で
    計算していた。**壁を引く相手が平らな奥行（108）で、上ケースの座ぐりは
    平面図の奥行（107.12）から引かれていた**ため、傾けたプレートは
    座ぐりより 0.217mm 大きく、手前の縁が壁に当たって落ちなかった
    （2026-08-10 に、干渉検査の許容を実測に合わせて締めたら出てきた）。
    左右方向も隙間 0 だった。**この案件で 3 度目の「平ら／平面図」の
    取り違え**（電池蓋 0.42mm、プレートの覆い、そしてここ）。
    """
    w, h = plate_size(key_w, key_h)
    fit_w = w - BEZEL_WALL * 2 - CLEARANCE          # 平面図で許される幅
    fit_h = plan_depth(h) - BEZEL_WALL * 2 - CLEARANCE   # 同・奥行
    t = radians(TILT_DEG)
    return fit_w, (fit_h - PLATE_T * sin(t)) / cos(t)

# 打鍵面の傾斜。プレートは平らに作って傾けて載せるので、
# 平面図（＝ケースの外形）では奥行が cos(TILT) 倍に縮む。
# これを見落とすとプレートがケースのリムを覆いきれない。
TILT_DEG = 7.3


def plan_depth(plate_depth):
    """平らなプレートを傾けたときの、平面図での奥行。"""
    return plate_depth * cos(radians(TILT_DEG))


def to_plan(pos):
    """プレート座標（平ら）の点を、平面図の座標へ写す。"""
    x, y = pos
    return (x, y * cos(radians(TILT_DEG)))

# --------------------------------------------------------------------------
# スイッチ開口
# --------------------------------------------------------------------------
SWITCH_CUTOUT = 14.0     # MX 標準
PLATE_T = 1.5

# --------------------------------------------------------------------------
# 基板
# --------------------------------------------------------------------------
# プレート外形より内側へ引く量（片側）。ケースの側壁 2.4mm の内側に収める
# 必要がある。1.0mm にしていて壁と 17,000mm^3 衝突した。
#
# ここに置くのは、プレート・ケース・基板の 3 つが同じ値を使う必要があるため。
# envelopes.py は build123d に依存していて KiCad の Python から読めないので、
# 基板生成（gen_pcb.py）から参照できる場所に無いと二重管理になる。
# --------------------------------------------------------------------------
# 上ケース（ベゼル）
# 決定の経緯は docs/hardware/decisions/2026-08-07-top-case.md
# 寸法の関係は tools/test_topcase_geometry.py が守る
# --------------------------------------------------------------------------
BEZEL_WALL = 1.6          # 上ケースの壁。2.4 だとプレートとの重なりが 0.23mm
BEZEL_OPENING_GAP = 1.5   # 開口をキー領域からどれだけ広げるか
BEZEL_TOP_FRONT = 17.5    # 前縁でのベゼル上面＝**手前端そのもの**。
                          # 実機の一次資料は 17mm と約 18mm に割れており、
                          # その間を採った（docs/hardware/dimensions.md）。
                          # 組み上げた立体の前縁が実際にこの値になることは
                          # test_front_edge_height が実測で見張る。
MOUNT_Y = 51.5            # ネジのボス中心。4 つの制約が同時に成立する唯一の帯

PCB_INSET = 3.0        # 左右。これ以上詰めるとキー領域が基板からはみ出す
# 前後は**もっと詰める。**取付ボス（y=±51.5, φ5 → 内端 49.0）を基板の外に
# 出すため。基板の縁が 51.0 のままだと 2mm 重なり、切り欠きが要る。
# キー領域の縁は 47.625、最も外のソケットも 45.3 までなので 49.0 で足りる。
PCB_INSET_Y = 5.3   # ボス φ5.6 の内端 48.7 に合わせる


def plate_positions(keys):
    """キー中心を CAD 座標（原点中心・Y 上向き）に直す。

    プレート・ケース・基板・取付位置の探索がすべてこの 1 つの関数を使う。
    座標変換を複数箇所に書くとずれる。
    """
    xs0 = min(k.x_mm - k.w_u * 19.05 / 2 for k in keys)
    xs1 = max(k.x_mm + k.w_u * 19.05 / 2 for k in keys)
    ys0 = min(k.y_mm - k.h_u * 19.05 / 2 for k in keys)
    ys1 = max(k.y_mm + k.h_u * 19.05 / 2 for k in keys)
    cx, cy = (xs0 + xs1) / 2, (ys0 + ys1) / 2
    return ([(k.x_mm - cx, cy - k.y_mm) for k in keys],
            plate_size(xs1 - xs0, ys1 - ys0))


# --------------------------------------------------------------------------
# スタビライザー
#
# プレートの開口と基板の逃げ穴が同じ位置に来る必要があるので、ここに置く。
# 以前ネジボスの位置をプレートとケースで別々に持っていて食い違わせた。
# 同じ寸法を 2 箇所に書かない。
#
# 値は Cherry の規格（0.47 インチ ＝ 11.938mm、0.75 インチ ＝ 19.05mm）。
# swillkb の key.go は 11.9 と丸めているが、基板用フットプリント
# （kiswitch）は 11.938 を使うため、厳密な方に揃える。差は 0.038mm。
#
# 2u 未満のキーにはスタビライザーを入れない（業界慣行）。
# 本設計で該当するのは 左Shift 2.25u / Enter 2.25u / L-Space 3u / R-Space 3u。
# --------------------------------------------------------------------------
STAB_OFFSET = {2.0: 11.938, 2.25: 11.938, 2.75: 11.938, 3.0: 19.05,
               6.25: 50.0, 7.0: 57.15}


# プレートのスタビ開口を、規格の輪郭から外へ広げる量（**片側**）。
#
# swillkb の標準パスは kerf=0（レーザの刃幅を後から入れる前提）。それを
# そのまま 3D プリントに使うと隙間ゼロで、入るかどうかが運任せになる
# （実形状の検査で 12 箇所・各 0.02〜0.03mm の膜として出た。open-gaps #30）。
#
# **スタビは基板保持。**フットプリントに φ3.048 / φ3.9878 の穴があり、
# クリップは基板に留まる。プレートは通すだけなので、広げてもガタつかない。
#
# **swillkb の標準パスは、実物のスタビより狭い。**（2026-08-10 に実測）
# 開口の胴は ±3.375（6.750mm）だが、kiswitch のハウジングは 6.804mm ある。
# 片側 0.027mm 足りない。これが #30 の「12 箇所・各 0.02〜0.03mm の膜」の
# 正体で、**逃げを 0.1 入れても実物に対しては 0.073 しか空かない。**
# 0.05 へ切り上げて足す（測り方は test_assembly の同名の検査）。
STAB_MODEL_OVERSIZE = 0.05

# 逃げの目標は、プレートと上ケースの嵌合（CLEARANCE = 両側合計 0.2mm）に
# 合わせて**実物に対して片側 0.1mm**。開口はそれより上の不足ぶん広く切る。
STAB_KERF = CLEARANCE / 2 + STAB_MODEL_OVERSIZE


def stab_offset_for(w_u):
    """幅 w_u のキーに要るスタビライザー半間隔。不要なら None。"""
    if w_u < 2.0:
        return None
    if w_u not in STAB_OFFSET:
        raise ValueError(
            f"{w_u}u のスタビライザー間隔が未定義。"
            "プレートと基板の両方に影響するので、足すときはここに足す")
    return STAB_OFFSET[w_u]


# --------------------------------------------------------------------------
# 取付ネジ（M2）
#
# ケース側はボスに下穴を切ってタッピング、プレート側はバカ穴。
# 位置は外周に沿って 6 箇所。キー開口と干渉しない位置に置く。
# --------------------------------------------------------------------------
# 熱圧入インサート（M2 / 外径 3.2mm）を埋める前提。
# **PLA に直接タッピングすると数回の開け閉めで舐める。**
# インサート外径 3.2mm に対して肉厚 1.2mm を確保すると φ5.6。
M2_INSERT_D = 3.2
M2_BOSS_D = 5.6          # ボス外径
M2_PILOT_D = 3.2         # ケース側の下穴。**熱圧入インサートの外径。**
                         # タッピング用の 1.7mm ではない
M2_CLEAR_D = 2.4         # プレート側のバカ穴（M2 に 0.4mm の逃げ）
# [記録のみ] ボスの位置は find_mounts.py の探索結果（MOUNT_POSITIONS）を
# 直接持つようになったので、この算出用の値はもう誰も読まない。
BOSS_WALL_OVERLAP = 1.0  # ボスを壁にめり込ませる量。接線接触を避けるため
# [記録のみ] **奥のネジは廃止してフックにした**（下の MOUNT_POSITIONS の注記）。
# 奥のボスが無いので、この値はもう効いていない。
REAR_BOSS_INSET = 9.0    # 後ろ側の中間ボスを、隅のボスからどれだけ内側へ置くか。
                         # 電池室（幅109mm）の外に出す必要がある。小さくしすぎると
                         # ボスが電池に食い込む
CASE_WALL = 2.4          # ボス位置の算出に要るのでここに置く


# --------------------------------------------------------------------------
# XIAO を子基板のどこへ置くか（**ケースと基板の両方が同じ値を使う**）
#
# open-gaps #28。XIAO を子基板の中央に置いていたため、USB のメス（レセプタクル）が
# 奥壁の外面から 8.9mm も奥にあった。プラグの金属は 6.5mm しかないので
# **2.4mm 届かず、樹脂の胴体（実測 12x7mm）を壁の穴（10x6mm）へ押し込まないと
# 挿さらない**という状態だった。普通の機器はメスが壁のすぐ内側にあり、
# 中へ入るのは金属だけ。
#
# 併せて open-gaps #23（アンテナが地板に挟まれている）にも効く。XIAO の
# アンテナは USB と反対の端にあるので、XIAO を奥へ寄せるほどアンテナは
# 本体基板の下から出る。
#
# **フットプリントの実寸から読んだ値**（pcb/lib/hhkb_split.pretty/XIAO_nRF52840）。
XIAO_OUTLINE_L = 21.5    # [確定] 外形（長手・USB←→アンテナ方向）
XIAO_OUTLINE_W = 18.3    # [確定] 外形（短手）
# パッドは端から 3.13mm 内側（y=±7.62 / 外形 ±10.75）までしか無い。
# **その「のりしろ」の範囲でなら、基板から外へ出しても全パッドが板に載る。**
XIAO_PAD_INSET = 3.13    # [確定] 外形の端から、いちばん端のパッドまで
XIAO_OVERHANG = 1.8      # XIAO を子基板の奥端より外へ出す量。
                         # 板は最後のパッドより 1.33mm 先まで残る


# チップアンテナ（青いセラミックの部品）の大きさ。**2026-08-09 に利用者が実測。**
# 概数で 3.5 x 1.5mm。**どちらが長手か（基板の長さ方向か幅方向か）は
# 写真から確定できなかった**ので、**大きいほうを両方に使う**（保守側）。
#
# ここが効くのは 2 箇所:
#   - アンテナが本体基板の下から出ているかの判定（長さ方向）
#   - 子基板の配線をアンテナの真下から外せるかの判定（幅方向）
ANTENNA_L = 3.5          # [暫定] 実測（大きいほうの辺。向き未確定）
ANTENNA_W = 3.5          # [暫定] 同上
# アンテナの、基板の幅方向の位置（XIAO の中心線からのずれ）。
#
# **2026-08-09 に利用者が実測。**「TX と印刷されている側の縁から青い部品の
# 中心まで 7.0mm」。XIAO の幅は 17.8mm なので中心は 8.9mm、ずれは
# 8.9 - 7.0 = 1.9mm。D6(TX) はフットプリントの x=-7.62 側なので符号は負。
#
# **写真からの読み（-1.7）より 0.2mm 大きかった。**この 0.2mm で、
# アンテナの下を通る配線が 1 本から 2 本に変わる。**測ってよかった値。**
#
# ⚠️ 測る基準は「左の縁」ではなく「**TX 側の縁**」。基板を裏返すと左右が
# 入れ替わり、結論が逆になる（一度そう書いて確認が要った）。
ANTENNA_X = -1.9         # [確定] 実測（TX 側の縁から 7.0mm）
ANTENNA_CLEAR = 0.5      # 配線をアンテナの縁からどれだけ離すか


def antenna_x_band():
    """配線を通してはいけない x の範囲（XIAO の中心線が 0）。"""
    half = ANTENNA_W / 2 + ANTENNA_CLEAR
    return ANTENNA_X - half, ANTENNA_X + half


def antenna_y_span(db_rear_y):
    """アンテナが占める Y の範囲（ケース座標・奥が +）。

    **アンテナは XIAO の「USB と反対の端」にある。**だから XIAO を奥へ
    寄せるほど、アンテナは本体基板の下から出る（open-gaps #23）。
    位置を 2 箇所で別々に計算しないよう、ここに 1 つだけ置く。
    """
    xiao_rear = db_rear_y + XIAO_OVERHANG
    lo = xiao_rear - XIAO_OUTLINE_L
    return lo, lo + ANTENNA_L


def xiao_y_offset(db_d):
    """子基板の中心から見た XIAO の中心 Y（奥が +）。

    **ケース（壁のポケット）と基板（フットプリントの位置）が、必ずこの
    1 つの式から座標を取る。**片方だけ動かすと、XIAO の端が壁を突き破るか、
    逆に届かなくなる。
    """
    return db_d / 2 - XIAO_OUTLINE_L / 2 + XIAO_OVERHANG


# 取付ネジの位置（原点＝プレート中心、Y 上向き、mm）
#
# **外周に等間隔で並べることはできない。** HHKB と同じ縁幅（左右 4.125mm）には
# M2 の穴・φ5 のボス・基板の縁が並ばないため。当初は外周に並べていて、
# 取付穴が基板の外形を 0.3mm はみ出していた。
#
# そこで、キーとキーの隙間（行ずれで階段状に空く分割境界側と、最下段の隅）に
# 置く。位置は tools/find_mounts.py が、キー配置とフットプリントの実寸から
# 総当たりで探して選んだもの。**推測ではなく探索の結果**。
#
# 奥の中央には置けない。電池室（幅 109mm）が横断しているため。電池を奥へ
# 置いたのは傾いた基板の下へ収めるための判断で、これはその代償。
# 代わりに長辺の中央を支える。
#
# 値を変えるときは tools/find_mounts.py --select をやり直すこと。
# tools/test_mounts.py が、この値が今も有効か（キーと干渉せず基板に収まるか）を
# 検査している。
# 取付ネジ。**手前の 3 本だけ。奥はフックで引っ掛ける。**
#
# 以前は 7 本を四方に置いていたが、14 本中 9 本がキーキャップの下に入り、
# 開けるのにキャップを外す必要があった（プレート開口 14mm を避けていたが、
# キャップ 18mm を考えていなかった）。
#
# 奥にも置こうとしたが、ボスの外端 y=54.00 が電池の手前端 y=52.10 と
# 1.90mm 重なる。逃がすにはコブを 20.4mm（全長 127.5mm）にする必要があり、
# 実機 120mm から離れすぎる。**奥はフックにした。**部品も印刷時間も減る。
#
# y = -MOUNT_Y は tools/test_topcase_geometry.py が守る 4 条件の帯。
# 本体基板をプレートへ締める柱の位置（open-gaps #36・2026-08-12）。
#
# **本体基板には固定具が 1 つも無かった。**上ケースのネジ 3 本は y=−51.5 で
# 基板の縁（−48.7）より外にあり、**基板に触れてもいない。**下の支えも無い。
# 保持は**スイッチ 54 本のピンの摩擦だけ**で、**スイッチを抜くとソケットの
# はんだに剥離力**がかかる——ホットスワップ基板でいちばんよくある壊れ方。
#
# **プレートの裏に柱を立て、下からネジで締める。**こうすると
# **ネジの頭が上面に出ない**（以前 7 本を四方に置いてキャップの下に入り、
# 開けるのにキャップを外す羽目になった失敗を繰り返さない）。剥離力は
# スイッチと基板の間で起きるので、**基板をプレートに締めるのが力の流れに沿う。**
#
# **位置は探索の結果**（推測ではない）。**実基板から全フットプリントの
# コートヤード**（左 93・右 116 個）を取り出し、それを避けた点から、
# **キーから最寄りの留め点までの最大距離を小さくする**ように選んだ:
#   左 6 本 → 最大 33.9mm ／ 右 8 本 → 最大 34.9mm
#
# ⚠️ **パッドと部品の bbox だけでは足りない。**最初それで選んだら、
# DRC が **Courtyards overlap 16 / NPTH inside courtyard 3** を出した
# （2026-08-12）。KiCad が見るのは**コートヤード**で、実装部品の 3D
# モデルの外形ではない。**穴自身のコートヤード半径 2.45mm** も要る。
# やり直すときは、実基板から GetCourtyard() で取り直すこと。
