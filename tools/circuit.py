"""回路を**データとして**宣言する。ここが回路の唯一の出所。

なぜ要るか
----------
この案件で最も高くついた見落としは、どれも回路の側にあった。

  - バルクコンデンサが無く、電池を使い切る前にブラウンアウトする
  - パスコンが無く、595 のノイズが行の入力へ回り込む
  - 595 の MR/OE が浮いていて、動かないか不安定になる

**3 つとも、私が指示されて見直すまで誰も気づかなかった。** 幾何には DRC と
干渉検査があるのに、回路には検査が 1 つも無かったのが理由。KiCad の ERC は
回路図が要るが、この案件では基板を Python が直接組んでいて回路図が存在しない。

そこで回路をここに宣言し、tools/test_circuit.py が電気的な規則を検査する。
基板を組むときもここを読むようにすれば、回路と基板が食い違うこともなくなる。

書き方
------
    PART(参照名, 種類, {端子名: ネット名})

**繋がないことにも意味がある端子（595 の未使用出力など）は
NC と書く。**書き忘れと区別がつかないと、浮きピンの検査ができない。
"""

import re
from pathlib import Path

# 電池は単3×2。新品のアルカリは 1 本 1.6V まで上がりうる。
BATT_CELLS = 2
BATT_V_MAX = 1.65 * BATT_CELLS
BATT_V_NOMINAL = 1.5 * BATT_CELLS   # [記録のみ] 公称値。判定は V_MAX / V_MIN で行う

# ショットキーの順方向電圧降下。**設計上の保守値。実測前。**
#
# **出所を直した（2026-08-08）。**以前は「SB240LES の値」と書いていたが、
# SB240LES はブレッドボード用に手元にあっただけの部品で、**本番では使わない**。
# 本番は B5819W（C8598・JLCPCB の基本部品）に決まった。
#
# B5819W のデータシートで保証されているのは **IF=1A で VF≤0.6V** だけ。
# **低電流での最大値は規定が無い。**特性グラフも 0.1A までしか描かれておらず
# （25℃・0.1A で約 0.28V）、実使用の 10〜15mA は図の外。
#
# したがって **0.4V を下げる根拠は無い。**下げるとブラウンアウトの危険が
# 出る（打ち止めが下がりすぎる）。0.28V の典型値に余裕を上乗せした保守値と
# して 0.4V を置く。**Task C4 で実測して詰める。**
#
# 実測して下げれば電池を長く使えるが、**発注をせき止める値ではない**。
# 基板には影響せず、打ち止めは設計値・文書上の値だから。
#
# この値は下げてよい（2026-08-11 に #34 で定義を直した）。打ち止めが
# `max(維持, 起動)` になったので、Vf を実測値に下げても打ち止めは
# 起動の限界より下がらない。下げれば維持側の見積もりが正確になるだけ。
SCHOTTKY_VF = 0.4        # [暫定] B5819W。実測は Task C4
MCU_V_MIN = 1.7                      # nRF52840 の動作下限
MCU_MARGIN = 0.1                     # 下限に対して残す余裕

# **上限。**3V3 ピンへ外から給電すると、載っているレギュレータを迂回して
# nRF52840 の VDD へ直接入る。データシートの推奨動作範囲は 1.7〜3.6V、
# 絶対最大定格は 3.9V。ここを超えると壊れる。
#
# **この上限を見る検査が無かった。**変異検査で `BATT_CELLS` を 2→3 に
# しても 271 件が全部通ったので分かった。3 本だと新品で 4.95V、
# ショットキーを引いて 4.55V が VDD に入る。
MCU_V_MAX = 3.6                      # 推奨動作範囲の上限
MCU_V_ABSMAX = 3.9                   # 絶対最大定格。超えたら壊れる

# **基板に載る IC の動作電圧範囲。**打ち止めはいちばん厳しい IC で決まる。
#
# **これを見ていなかった。**打ち止めをマイコンの 1.7V だけから計算していて、
# 74HC595 の下限 2.0V を見落としていた。レールは打ち止めで 1.8V まで下がる
# ので、**シフトレジスタが規格外で動く**ことになっていた（列が正しく
# 駆動されず、キーが反応しない）。
#
# 74HC を 74LVC に替えて解いた。LVC は 1.1〜3.6V で、レールの全域を覆う。
# フットプリントは同じ TSSOP-16 なので基板は変わらない。
# 上限 3.6V に対してレールの最大は 2.90V（USB 時 3.3V）で内側。
IC_SUPPLY_RANGE = {                  # 種類 → (下限V, 上限V)
    "74LVC595": (1.1, 3.6),          # SN74LVC595A（C52287685）
    "xiao_nrf52840": (MCU_V_MIN, MCU_V_MAX),
}

# **使い切れる下限は、望みではなく回路で決まる。**
#
# 当初 0.9V/本（＝完全放電）と書いていたが、test_circuit の
# test_the_mcu_still_runs_on_depleted_cells が「マイコンへ 1.40V しか
# 届かない（下限 1.7V）」と検出した。直列のショットキーが降下するぶん、
# 電池の電圧はマイコンの下限より高いところで打ち止めになる。
#
#   必要な電池電圧 = マイコン下限 1.7V ＋ 余裕 0.1V ＋ ショットキー降下
#
# 降下 0.4V なら 2.20V（1.10V/本）。アルカリ単3 を低負荷で使う場合、
# ここで止めると容量の 1 割ほどを残すことになる。
#
# 逆流防止は安全のため外せないので、この 1 割は**ショットキーを選んだ
# 代償**として受け入れる。
#
# **以前ここには「0.4V はデータシートの定格電流での値で、10mA では 0.2V
# ほどまで下がるはず」と書いてあったが、根拠が無かった。**B5819W の
# データシートは IF=1A の 0.6V しか保証しておらず、特性グラフも 0.1A まで
# （25℃ で約 0.28V）。実使用の 10〜15mA は図の外。**Task C4 で実測する。**
# 実測できたら SCHOTTKY_VF を下げ、下限もそのぶん下げられる。
# マトリクスのダイオードの順方向降下。**行に届く電圧はここで決まる。**
#
# 列 → キー → ダイオード → 行 と流れるので、行に届くのは
# （レール − Vf）。nRF52840 の VIH は 0.7 x VDD なので、
#
#     レール − Vf ≧ 0.7 × レール   →   レール ≧ Vf / 0.3
#
# **BAT46W の保証値を使う。**VF ≦ 0.25V @ IF=0.1mA（走査電流そのもの）。
# 温度の余裕 0.05V を足して 0.30V。→ 必要なレールは 1.17V で、
# **マイコンの 1.80V が律速に戻る。実測は要らない。**
#
# 1N4148W（シリコン）だと 1mA 未満の最大値が規定されておらず、典型曲線から
# 0.50V ＋ 余裕 0.05V で 0.55V。**レール 2.00V が要り、マイコンより先に
# マトリクスが落ちる**＝キーが 1 つずつ反応しなくなる壊れ方だった。
# 差し戻すときは 0.55 に戻す（tools/parts.py のバックアップの項）。
MATRIX_DIODE_VF = 0.30   # BAT46W の保証 0.25V @ 0.1mA ＋ 温度の余裕 0.05V

# 列を駆動する側の出力降下。
#
# **SN74LVC595A のデータシートの保証値: IOH = -100µA で VOH ≧ VCC - 0.2V**
# （VCC 1.1〜3.6V）。走査電流は行のプルダウン 11〜16kΩ に流れる約 100µA
# なので、この条件そのもの。
#
# **0.05V と置いていたが 4 倍の誤りだった**（「CMOS だからほぼ VCC のはず」
# という推測。2026-08-08 に datasheet で訂正）。
COL_DRIVER_DROP = 0.20

# **使い切れる下限は、望みではなく回路で決まる。**
#
# 3 つの制約のうち、いちばん厳しいものがレールの下限になる。
#
#   マイコン        MCU_V_MIN + MCU_MARGIN
#   IC の動作範囲   IC_SUPPLY_RANGE の下限
#   マトリクス      (MATRIX_DIODE_VF + COL_DRIVER_DROP) / 0.3
#
# **1 つだけ見て決めると足をすくわれる。**実際、マイコンだけを見ていて
# 74HC595 の 2.0V とマトリクスの制約を 2 回とも見落とした。
# ホットスワップソケットの最低使用電圧。
#
# **CPG151101S11 のデータシート: Voltage 12V max / 2V DC min、接点は錫めっき。**
# 錫は低電圧だと酸化膜を破れず接触不良になりうる（保証範囲の下限）。
# ダイオードやマイコンの下限と違って「割ると必ず動かない」ではないが、
# **メーカーが保証していない領域**なので制約に入れる。
SOCKET_V_MIN = 2.00

_RAIL_FLOOR = max(
    MCU_V_MIN + MCU_MARGIN,
    max(lo for lo, _hi in IC_SUPPLY_RANGE.values()),
    (MATRIX_DIODE_VF + COL_DRIVER_DROP) / 0.3,
    SOCKET_V_MIN,
)
# **2026-08-11 に、可変電源で検証した。足りている。**
#
#   維持の限界（繋がったまま下げる）  1.95V（レール 1.76V）
#   **起動の限界**（切って入れ直す）  **10Ω のとき 2.15〜2.25V**（直接実測）
#
# **打ち止めを決めるのは起動のほう。**起動は走査・広告で 2.7mA、瞬間は
# もっと引くので、内部抵抗の影響を強く受ける。
# **スリープ復帰も起動と同じ手順を踏む。**
#
# 本番の電池が打ち止め付近で持つ内部抵抗は 5〜10Ω（実測 2.68 / 9.18Ω）で、
# **その範囲に直接の実測がある。外挿していない。**
#
# ⚠️ **温度は試験していない。**冷えると内部抵抗が 2〜3 倍になり、交点が
# 上がる。**冬の朝に起動しない**恐れ → open-gaps #33。
BOOT_V_MIN = 2.20    # 起動の限界。10Ω・可変電源で直接実測（帯 2.15〜2.25 の中央）
BOOT_MARGIN = 0.20   # 誤差ぶんの余裕。#33（低温）と分圧の誤差を実測したら見直す

# **打ち止めは「維持できる電圧」と「起動できる電圧」の高いほう**
# （2026-08-11・open-gaps #34 で定義を直した。利用者の判断）。
#
# 装置が実際に止まるのは維持ではなく起動で決まる（スリープ復帰も起動と
# 同じ手順を踏む）。旧定義 `_RAIL_FLOOR + SCHOTTKY_VF` だけだと、Vf を
# 実測値 0.18V に直した瞬間に打ち止めが 2.18V となり、**自分で再起動
# できない電圧まで使い切ってから止まる**装置になる。max で両方を見れば、
# どちらの定数を実測で詰めても矛盾しない。
# いまはどちらも 2.40V で、値は旧定義と同じ。
BATT_V_MIN = max(_RAIL_FLOOR + SCHOTTKY_VF, BOOT_V_MIN + BOOT_MARGIN)

# マトリクスのダイオードの逆漏れ（保証値）と、行のプルダウン。
#
# **ゴースト防止はここで決まる。**同じ行で n 個同時に押されると、
# 押されていない列側のダイオードの逆漏れが n 個ぶん足し算になり、
# 行の High を引き下げる。引き下げが（行の High − VIH）を超えると誤検出。
# BLE 送信中の電圧降下。**打ち止めのレールとマイコンの下限の差が、これを
# 覆う必要がある**（2026-08-11 に比較相手を直した。下記）。
#
# 降下は「電流 × 電池の内部抵抗」で決まる。**バルクコンデンサでは消せない。**
# コンデンサが効くのは τ = R×C より短い間だけ。
#
# ⚠️ **2026-08-11 に内部抵抗を実測したら、想定の 6 倍あった。**
# それに伴い、上の τ の話も数字が変わる（下の実測の欄を読むこと）。
BLE_TX_CURRENT = 0.015       # [暫定] 送信中の消費電流。Task C4 で実測する

# **電池末期の内部抵抗（2 本ぶん合計）。**
#
# **2026-08-11 に実測した**（使い古しのアルカリ 2 組。100Ω×4 本を並列にした
# 25.0Ω を負荷にして、開放電圧と負荷時の電圧の差から求めた）。
#
#   1.34V/本（Panasonic EVOLTA NEO LR6(INJ)）  2.69→2.43V / 97mA → **2.68Ω**
#   1.07V/本（三菱電機 LR6(N)）                2.16→1.58V / 63mA → **9.18Ω**
#
# **9.18 を採る。**打ち止めは 1.20V/本 なので、**1.07V/本 は製品が到達する前に
# 止まっている領域**＝本番で経験する内部抵抗は必ずこれより小さい。**保守側。**
#
# **補間しない。**1.20V/本 での値は線形補間で 6.05Ω、対数補間で 5.07Ω と
# 形の仮定で動く。**測った点をそのまま使うほうが、推論が 1 つ減る。**
#
# ⚠️ **銘柄と温度で変わる。**アルカリとマンガンで 5 倍、冷えると増える。
# だからここは「典型値」ではなく「悪い側の境界」を置く。
BATT_ESR_END = 9.2           # 実測（1.07V/本・打ち止めより下＝保守側）

MATRIX_DIODE_IR = 0.3e-6     # BAT46W の保証 0.3µA @ VR=1.5V（25℃）
# nRF52840 の内部プルダウン RPD は **11 / 13 / 16kΩ（min/typ/max）**
# （出典: nRF52840 Product Specification v1.1 の GPIO 電気的仕様）。
#
# **ばらつきの最悪は項目によって逆を向く。**
#
#   ゴースト・settling … 抵抗が**大きい**ほうが最悪（16kΩ）。
#                        漏れ電流 x 抵抗 の引き下げが増え、放電も遅くなる
#   VF（行が High に届くか）… 抵抗が**小さい**ほうが最悪（11kΩ）。
#                        流れる電流が 132µA に増えて VF が上がる。
#                        保証は 0.25V @ 100µA、設計値 0.30V なので覆われる
#
# ここは 16kΩ を置く。**典型の 13kΩ で計算していて 19% 甘かった**
ROW_PULLDOWN = 16_000

DIVIDER_R_HIGH = 1_000_000
DIVIDER_R_LOW = 1_000_000

# 595（SN74LVC595A）のピン名。データシートの呼び名に合わせる。
_595_OUTPUTS = ["Q0", "Q1", "Q2", "Q3", "Q4", "Q5", "Q6", "Q7"]


def _shift_register(ref, cols, first_col, serial_in, serial_out):
    """595（SN74LVC595A）を 1 個ぶん。cols 本ぶん列に繋ぎ、残りは NC。

    **MR は VCC、OE は GND に必ず固定する。**浮かせると、MR はノイズで
    中身が消え、OE は出力が High-Z になって全キーが反応しない。
    """
    pins = {
        "VCC": "V3V3", "GND": "GND",
        "MR": "V3V3",          # マスタリセット。Low で消える
        "OE": "GND",           # 出力許可。Low で有効
        "DS": serial_in,
        "SH_CP": "SPI_SCK",
        "ST_CP": "CS",
        "Q7S": serial_out,     # 数珠つなぎの送り出し
    }
    for i, name in enumerate(_595_OUTPUTS):
        pins[name] = f"COL{first_col + i}" if i < cols else "NC"
    return (ref, "74LVC595", pins)


# 電子部品の参照名（基板上の名前）。
#
# **接頭辞で走査しない。**`D` や `SW` で拾うとダイオード 61 個と
# キースイッチ 61 個を巻き込む。この案件で 4 回起きた事故。
#
# **生成側（gnd_fanout）と検査側（test_pcb）の両方が使う。**別々に持つと
# 片方だけ直して静かにずれる。実際、電源スイッチが SW_PWR から
# SW_PWR_1 / SW_PWR_2 に変わったとき、両方を直す必要があった。
# ⚠️ **`J_MAIN` が抜けていた**（2026-08-14 に追加）。FFC の両端のうち
# **主基板側の `J_DB` だけがあって、子基板側の `J_MAIN` が無かった。**
# そのせいで `gnd_fanout.place` が子基板の FFC に GND ビアを打たず、
# **FFC の GND パッドはベタに繋がっていなかった**（`_prewire_power` の
# 1.2mm の枝が出るだけで、その先に何も無い）。
# 対になるものは対で書く。片方だけあると、こうして静かに落ちる。
ELEC_REF = re.compile(
    r"U\d+|C_[A-Z0-9]+|R_[A-Z]+|D_PWR|SW_PWR_\d|J_DB|J_MAIN|BT1_[+-]")


# ケースの中で配線し、基板側はランド 2 個で受ける部品。
#
# **生成側（gen_pcb）と検査側の両方が使う。**別々に持つと、部品を足した
# ときに片方だけ直して静かにずれる（実際、電源スイッチをランドに変えた
# とき、検査 6 件が BT1 しか知らずに落ちた）。
WIRE_PAD_KINDS = {"battery_holder", "wire_pads"}


def board_refs(ref, kind, pins):
    """その部品が基板上で名乗る参照名。ランド 2 個の部品は 2 つに分かれる。"""
    if kind in WIRE_PAD_KINDS:
        return [f"{ref}_{p}" for p in pins]
    return [ref]


def mechanical_refs(half):
    """基板に載るが**回路には入らない**部品の参照名。スタビと取付穴。

    以前は検査側が `startswith(("H", "ST"))` で除外していた。CLAUDE.md が
    禁じている接頭辞での走査で、**`HACK_ROGUE` のような名前が素通りした**
    （実際に置いて確かめた）。しかも `"H"` は本体基板に 1 つも該当が無く、
    効いていない除外だった（`H` は子基板の取付穴）。

    除外をやめて**あるべきものを宣言する**と、逆向きも効く。
    スタビライザが 1 個欠けても同じ検査が落ちる（以前は誰も見ていなかった）。

    参照名の番号はキーの通し番号。gen_pcb が `ST{i}` を振るのと同じ
    `keymap_order` の並びから作る。
    """
    from interface import stab_offset_for
    from layout import load_layout, split_halves
    from matrix import keymap_order

    path = Path(__file__).resolve().parent.parent / "layout/hhkb_split.json"
    left, right = split_halves(load_layout(str(path)))
    keys = keymap_order(left if half == "left" else right)
    # 取付穴（H0..）。**2026-08-12 に足した**（open-gaps #36。基板を
    # プレート裏の柱へ下から締める）。宣言しないと
    # test_nothing_on_the_board_is_undeclared が落ちる——**それでいい。**
    # 基板に物を足したら、ここにも書く。
    from interface import pcb_mount_positions

    return ({f"ST{i}" for i, k in enumerate(keys, start=1)
             if stab_offset_for(k.w_u) is not None}
            | {f"H{i}" for i in range(len(pcb_mount_positions(half)))})


def netlist(half):
    """その半分の回路。[(参照名, 種類, {端子: ネット}), ...] を返す。"""
    n_cols = 6 if half == "left" else 9
    parts = [
        # ---- 電源 ----
        # **この基板に電源部品は 1 つも無い**（2026-08-14・open-gaps #41）。
        #
        # 電池・スイッチ・ショットキー・分圧は**全部 子基板にある**。
        # ここは FFC 経由で V3V3 を受け取るだけで、消費するのは
        # **595 の走査 約 100µA だけ**（parts-audit 7）。
        #
        # なぜ子基板側に集めたか（利用者の指摘で判明した順）:
        #
        #   1. **消費者は XIAO で、それは子基板にいる。**起動と BLE の
        #      初期化で **2.0〜2.5mA を継続**して引き（task-c4-c5 測定 C）、
        #      送信で 10〜15mA のパルス（electrical-design 1-5）。
        #      595 の 100µA とは 100 倍以上ちがう。
        #      **主基板で整流すると、その mA 級が FFC の 0.2mm 1 本を
        #      100mm 渡ることになる。**逆に子基板で整流すれば、FFC を
        #      渡るのは 595 のぶん（約 100µA）だけ——150 分の 1。
        #   2. **継続的な mA はコンデンサでは供給できない**（同資料の訂正）。
        #      C_BULK を子基板へ移しても、この電流は導体で運ぶしかない。
        #   3. **電池もスイッチも子基板のすぐ隣にある**（実測: スイッチ→
        #      子基板の縁 左 4.0mm / 右 20.7mm）。リード線は**短くなる**。
        #   4. **VBATT_SENSE が FFC を渡らなくなる。**500kΩ の高インピー
        #      ダンス信号を 100mm のフラットケーブルで SPI_SCK の隣に
        #      並べて運ぶ、という形自体が消える。
        #   5. ショットキーの隔離点が **XIAO の 3V3 パッド直近**になる
        #      （USB 接続時に 3V3 が 3.3V へ上がって逆バイアスになる、
        #      という仕組みの節点そのもの）。
        #   6. 主基板の帯が空き、**SPI が U1/U2 まで通れるようになる**
        #      （電源 5 点が帯を塞いで COL3/COL4 を押し出していた）。
        #
        # ⚠️ **ここに電源部品を戻さないこと。**戻すなら上の 6 つを
        # 全部ひっくり返せるかを先に示す。過去に踏んだ跡:
        #   - `C_MCU` … この基板に MCU は無いのに MCU のパスコンを名乗った
        #   - `C_RAIL` … 改名したが J_DB から 70mm 離れ C_U1 の重複だった
        #   どちらも「名前が役割を偽ったまま基板に残る」形（#39/#40/#41）。
        #
        # パスコンは IC ごとに 1 個（C_U1 / C_U2）で足りている。
        # **3 個目の V3V3-GND を足さないこと。**
    ]

    # ---- シフトレジスタ ----
    if half == "left":
        parts.append(_shift_register("U1", n_cols, 0, "SPI_MOSI", "NC"))
        parts.append(("C_U1", "cap_100n", {"1": "V3V3", "2": "GND"}))
    else:
        # 最上段が 9 キーあるので 9 列要る。2 個を数珠つなぎにする。
        parts.append(_shift_register("U1", 8, 0, "SPI_MOSI", "U1_U2"))
        parts.append(_shift_register("U2", 1, 8, "U1_U2", "NC"))
        parts.append(("C_U1", "cap_100n", {"1": "V3V3", "2": "GND"}))
        parts.append(("C_U2", "cap_100n", {"1": "V3V3", "2": "GND"}))

    # ---- 子基板へのケーブル ----
    # 並び順は docs/hardware/decisions/2026-08-07-daughterboard.md のとおり。
    # 最も速い SCK を GND の隣に置いてループ面積を小さくする
    # （**両端を GND にはできない**——下の注のとおり交差が戻る）。
    parts.append(("J_DB", "ffc_12p", {
        # **並びは配線の順序で決まる。**子基板では FFC が手前、XIAO の
        # パッドが左右 2 列。手前から上がる配線は、近いパッドへ行くものほど
        # 外側を通す必要がある。ピン順がそれと逆だと交差する（最初の並びで
        # 6 箇所が短絡した）。左群(2-7) は左列を y の大きい順、右群(8-12) は
        # 右列を y の小さい順。GND はベタで受けるので順序に影響しない。
        # その制約の中で SCK(3) の隣を GND(2) にしてある（ループ面積を
        # 小さく）。**両端を GND にはできない。**そうすると交差が戻る。
        # 1 番の CS は 1 スキャンに 1 回しか動かないので端に置く害が最小。
        # **ROW4 は右群にいる**（open-gaps #23・D9 移設）。ROW4 の行き先が
        # XIAO の右列 D9 になったので、左群のままだと横枝が左群の縦線を
        # 8 箇所で横切る（DRC で実測）。右群の並び（前→奥＝D7,D8,D9,D10,3V3）
        # に合わせて 4 番へ挿し、後続を 1 つずつ繰り下げた。
        # **ROW を連続 5 ピンにし、行バスの y 順に並べた**（2026-08-14・#41）。
        # 以前は ROW4 だけ 4 番に飛んでいて（D9 移設の名残）、行バスから
        # J_DB へ降りる枝が交差していた（左の未配線 2 本の原因）。
        # 6 番は空き。使い道は検討中——**勝手に埋めないこと。**
        "1": "CS", "2": "GND", "3": "SPI_SCK", "4": "SPI_MOSI",
        "5": "V3V3", "6": "NC",
        "7": "ROW0", "8": "ROW1", "9": "ROW4", "10": "ROW3", "11": "ROW2",
        "12": "GND",
    }))

    # ---- マトリクス ----
    # col2row。列 → スイッチ → ダイオード → 行。
    n_keys = 27 if half == "left" else 34
    from matrix import assignments
    for i, (r, c) in enumerate(assignments(half), start=1):
        parts.append((f"SW{i}", "keyswitch", {"1": f"COL{c}", "2": f"SW{i}_D"}))
        parts.append((f"D{i}", "diode", {"A": f"SW{i}_D", "K": f"ROW{r}"}))
    assert len([p for p in parts if p[1] == "keyswitch"]) == n_keys

    return parts


